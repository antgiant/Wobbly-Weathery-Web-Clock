    const json = '{"latitude":40.7,"current":{' + fields.filter((k) => k in b).map((k) => `"${k}":${b[k]}`).join(',') + ',"time":"2026-06-21T12:00"}}';
    lines.push(['wlive', i, json, row(W.mapOpenMeteo(b, null))].join('\t'));

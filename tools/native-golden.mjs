// Writes native/core/tests/golden.tsv: inputs and the answers the WEB code gives, for the native (Rust) core to reproduce exactly.
// The native version must agree with the page on brightness (js/sky/dim.js) and countdown digits (js/countdown.js); these vectors are how that
// is checked (cargo test in native/core, and tests/unit/native-golden.test.mjs keeps the file current).
//   node tools/native-golden.mjs            write it        node tools/native-golden.mjs --check   fail if out of date
import fs from 'fs';
import path from 'path';
import '../tests/lib/astronomy.mjs';
import { installDomStub } from '../tests/lib/dom-stub.mjs';
installDomStub({});
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const { nightness, brightnessAt } = await import('../js/sky/dim.js');
const C = await import('../js/countdown.js');
const { easing } = await import('../js/easing.js');
const { dd } = await import('../js/config.js');

const lines = ['# Generated by tools/native-golden.mjs from the web code: do not edit. Fields are tab-separated; "nan" is no value.'];
const num = (x) => (x === null || x === undefined || Number.isNaN(x) ? 'nan' : String(x));
const H = 3600e3, D0 = Date.UTC(2026, 5, 21, 0, 0, 0), at = (h) => D0 + h * H;

// ---- brightness: a normal day (rise 06:00, set 18:00), a long summer day, polar day / night, a missing event ----
const evAround = (now, rise, set) => {
  const rises = [-24, 0, 24].map((d) => at(rise + d)), sets = [-24, 0, 24].map((d) => at(set + d));
  const last = (a) => a.filter((x) => x <= now), next = (a) => a.filter((x) => x > now);
  const ms = (a, f) => (a.length ? f(...a) : null);
  const d = (x) => (x === null ? null : new Date(x));
  return { prevRise: d(ms(last(rises), Math.max)), prevSet: d(ms(last(sets), Math.max)), nextRise: d(ms(next(rises), Math.min)), nextSet: d(ms(next(sets), Math.min)) };
};
const evOf = (ev) => ['prevRise', 'prevSet', 'nextRise', 'nextSet'].map((k) => num(ev[k] ? +ev[k] : null));
const cases = [];
for (const [rise, set] of [[6, 18], [4.5, 21.25], [7.75, 16.5]]) for (let h = 0; h <= 48; h += 0.25) cases.push([at(h), evAround(at(h), rise, set), 0]);
cases.push([at(12), { prevRise: null, prevSet: null, nextRise: null, nextSet: null }, 40], [at(12), { prevRise: null, prevSet: null, nextRise: null, nextSet: null }, -20], [at(12), { prevRise: null, prevSet: null, nextRise: null, nextSet: null }, -6], [at(12), null, 10]);
cases.push([at(30), { prevRise: null, prevSet: new Date(at(18)), nextRise: null, nextSet: null }, 0], [at(30), { prevRise: new Date(at(6)), prevSet: null, nextRise: null, nextSet: new Date(at(42)) }, 0]);
for (const [t, ev, alt] of cases) for (const minutes of [15, 45, 120]) {
  lines.push(['nightness', num(t), ...evOf(ev || {}), num(alt), minutes, num(nightness(t, ev, alt, minutes))].join('\t'));
}
for (const [t, ev, alt] of cases.filter((_, i) => i % 7 === 0)) for (const [day, night] of [[1, 0.25], [0.8, 0.1], [1, 1], [0.05, 2], [0.5, 0.5]]) {
  lines.push(['brightness', num(t), ...evOf(ev || {}), num(alt), 45, day, night, num(brightnessAt(t, ev, alt, day, night, 45))].join('\t'));
}

// ---- countdown digits ----
const secs = [0, 1, 59, 60, 61, 3599, 3600, 3661, 43200, 86399, 86400, 86401, 90061, 86400 * 9 + 3600 * 7 + 65, 86400 * 99 + 86399, 86400 * 100, 86400 * 100 + 5, 86400 * 365 + 7261, 86400 * 999 + 86399];
for (const s of secs) for (const show of [true, false]) {
  const g = C.groupsFor(s, show), sl = C.slotsFor(s, show);
  lines.push(['groups', s, show ? 1 : 0, g.map((x) => x.join(',')).join('|')].join('\t'));
  lines.push(['slots', s, show ? 1 : 0, `${sl.x.join(',')};${sl.h.join(',')};${sl.m.join(',')};${sl.s.join(',')};${['x', 'h0', 'm', 's'].map((k) => (sl.show[k] ? 1 : 0)).join('')}`].join('\t'));
  lines.push(['units', s, show ? 1 : 0, C.unitsFor(s, show)].join('\t'));
}
for (const [target, now] of [[10000, 4000], [10000, 10000], [10000, 10001], [10500, 10000], [1e6, 0], [5, 9]]) lines.push(['secondsleft', target, now, C.secondsLeft(target, now)].join('\t'));

// ---- the digit morph: the page's easing (easeInOutBack over 15 steps) and the blend of two digit shapes ----
for (let step = 0; step <= 15; step++) lines.push(['ease', step, 15, num(easing.easeInOutBack(null, step, 0, 1, 15))].join('\t'));
for (const [a, b] of [[0, 1], [1, 2], [2, 3], [5, 6], [9, 0], [7, 4]]) for (const step of [0, 1, 4, 8, 11, 14, 15]) {
  const e = easing.easeInOutBack(null, step, 0, 1, 15), m = dd[a].map((v, i) => v + e * (dd[b][i] - v));
  lines.push(['morph', a, b, step, m.map((v) => v.toFixed(9)).join(',')].join('\t'));
}

// ---- the sun: height and direction (geometric, no refraction) and the events around a moment, from the astronomy library the page uses ----
const { sunEvents } = await import('../js/sky/sunpath.js');
const PLACES = [[40.7, -74], [-33.9, 151.2], [64.15, -21.94], [1.35, 103.8], [-0.18, -78.47], [51.5, -0.13], [69.65, 18.96], [35.7, 139.7]];
const MOMENTS = ['2026-03-20T12:00:00Z', '2026-06-21T03:30:00Z', '2026-06-21T18:10:00Z', '2026-09-23T06:45:00Z', '2026-12-21T00:20:00Z', '2026-12-21T15:55:00Z', '2026-05-05T22:00:00Z'];
for (const [lat, lon] of PLACES) {
  const obs = new Astronomy.Observer(lat, lon, 0);
  for (const iso of MOMENTS) {
    const d = new Date(iso), t = Astronomy.MakeTime(d), eq = Astronomy.Equator('Sun', t, obs, true, true), hz = Astronomy.Horizon(t, obs, eq.ra, eq.dec, null);
    lines.push(['sunpos', lat, lon, +d, hz.altitude.toFixed(5), hz.azimuth.toFixed(5)].join('\t'));
    const ev = sunEvents(d, lat, lon, 0);
    lines.push(['sunevents', lat, lon, +d, ...['prevRise', 'prevSet', 'nextRise', 'nextSet'].map((k) => num(ev[k] ? +ev[k] : null))].join('\t'));
  }
}

// ---- local time: the wall clock of a zone at a moment, from Intl (what the page's js/timezone.js shows) ----
const ZONES = ['America/New_York', 'Europe/London', 'Australia/Sydney', 'Asia/Kolkata', 'Asia/Kathmandu', 'America/Sao_Paulo', 'Pacific/Auckland', 'Europe/Paris', 'Asia/Tokyo', 'America/Phoenix', 'UTC', 'America/Los_Angeles', 'Pacific/Chatham'];
const WHEN = ['2008-03-09T06:59:59Z', '2008-03-09T07:00:00Z', '2015-11-01T05:59:59Z', '2015-11-01T06:00:00Z', '2024-01-15T12:00:00Z', '2024-03-10T06:59:59Z', '2024-03-10T07:00:00Z', '2024-03-31T00:59:59Z', '2024-03-31T01:00:00Z', '2024-10-27T00:59:59Z', '2024-10-27T01:00:00Z', '2026-04-05T15:00:00Z', '2026-06-21T12:00:00Z', '2026-10-04T15:59:59Z', '2026-10-04T16:00:00Z', '2026-11-01T05:59:59Z', '2026-11-01T06:00:00Z', '2026-12-31T23:59:59Z', '2030-07-04T00:00:00Z', '2035-03-11T07:00:00Z', '2035-11-04T06:00:00Z'];
for (const z of ZONES) {
  const f = new Intl.DateTimeFormat('en-US', { timeZone: z, hourCycle: 'h23', hour: 'numeric', minute: 'numeric', second: 'numeric' });
  for (const iso of WHEN) { const d = new Date(iso), p = Object.fromEntries(f.formatToParts(d).map((x) => [x.type, Number(x.value)])); lines.push(['tz', z, Math.floor(+d / 1000), `${p.hour % 24},${p.minute},${p.second}`].join('\t')); }
}

// ---- countdown mode as the page runs it (js/countdown.js, in New York time): which phase, and the digits shown ----
{
  const keep = process.env.TZ; process.env.TZ = 'America/New_York';
  const targets = ['2026-12-25T08:00', '2026-03-08T01:30', '2026-11-01T00:00', '2026-06-21T23:59', '2027-01-01T00:00'];
  for (const target of targets) {
    const tgt = C.parseTarget(target);
    for (const delta of [-90 * 86400e3, -86400e3 - 3661e3, -3600e3, -61e3, -1e3, 0, 1e3, 3600e3, 12 * 3600e3, 23 * 3600e3 + 59 * 60e3, 24 * 3600e3, 30 * 3600e3, 3 * 86400e3]) {
      const now = tgt + delta, phase = C.phaseOf(tgt, now), left = C.secondsLeft(tgt, now);
      const show = (sec) => (phase === 'counting' ? C.textOf(C.groupsFor(left, sec)) : phase === 'done' ? '00:00' : 'time');
      lines.push(['countdown', target, now, phase, show(true), show(false)].join('\t'));
    }
  }
  if (keep === undefined) delete process.env.TZ; else process.env.TZ = keep;
}

// ---- weather: the page's presets, and how it maps an Open-Meteo "current" block (js/sky/weather.js) ----

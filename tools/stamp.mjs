// Stamps the app's version into js/version.js. The version is a number that goes up whenever any file of the app changes,
// plus a short hash of those files, so "which version is this?" has one definite answer: the page shows it (Settings ->
// Presets -> About), and the service worker names its cache after it.
//   node tools/stamp.mjs          update js/version.js if the files changed (npm test and npm run stamp do this)
//   node tools/stamp.mjs --check  only check it is current (CI): exit 1 if not
import fs from 'fs';
import path from 'path';
import crypto from 'crypto';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const out = path.join(root, 'js/version.js');

/** The files that make up the app: everything the service worker saves, plus the worker itself, minus version.js. */
export function appFiles() {
  const sw = fs.readFileSync(path.join(root, 'sw.js'), 'utf8');
  const list = sw.slice(sw.indexOf('const PRECACHE = ['), sw.indexOf('];', sw.indexOf('const PRECACHE')));
  const files = [...list.matchAll(/'([^']+)'/g)].map((m) => m[1]).map((u) => (u === './' ? 'index.html' : u));
  return [...new Set([...files, 'sw.js'])].filter((f) => f !== 'js/version.js').sort();
}

export function hashOfApp() {
  const h = crypto.createHash('sha256');
  for (const f of appFiles()) { h.update(f + '\0'); h.update(fs.readFileSync(path.join(root, f))); h.update('\0'); }
  return h.digest('hex').slice(0, 8);
}

export function readVersion() {
  try {
    const t = fs.readFileSync(out, 'utf8');
    return { number: +/number: (\d+)/.exec(t)[1], hash: /hash: '([0-9a-f]+)'/.exec(t)[1], built: /built: '([\d-]+)'/.exec(t)[1] };
  } catch { return { number: 0, hash: '', built: '' }; }
}

const render = (v) => `// Generated by tools/stamp.mjs: do not edit. The number goes up each time any file of the app changes; the hash is of those files.
// Loaded as a plain script by the page and by the service worker (importScripts), so it works in both.
globalThis.APP_VERSION = { number: ${v.number}, hash: '${v.hash}', built: '${v.built}' };
`;

const isMain = process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname);
if (isMain) {
  const cur = readVersion(), hash = hashOfApp();
  if (cur.hash === hash) { console.log(`version ${cur.number} (${hash}) is current`); process.exit(0); }
  if (process.argv.includes('--check')) { console.error(`js/version.js is stale (it says ${cur.hash}, the files are ${hash}): run npm run stamp`); process.exit(1); }
  const next = { number: cur.number + 1, hash, built: new Date().toISOString().slice(0, 10) };
  fs.writeFileSync(out, render(next));
  console.log(`version ${cur.number} -> ${next.number} (${hash})`);
}

// Writes schema/settings.json from schema/settings.js and schema/presets.js: the settings and presets as plain data, for the native
// version (and its command line, man page and tests) and anything else that is not JavaScript.
//   node tools/schema-json.mjs            write it        node tools/schema-json.mjs --check   fail if it is out of date (CI)
import fs from 'fs';
import path from 'path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const { SETTINGS } = await import('../schema/settings.js');
const { PRESET_LIST } = await import('../schema/presets.js');

export const render = () => JSON.stringify({
  note: 'Generated by tools/schema-json.mjs from schema/settings.js and schema/presets.js: do not edit. Run `npm run schema`.',
  settings: SETTINGS,
  presets: PRESET_LIST.map((p) => ({ id: p.id, name: p.name, note: p.note, set: p.set })),
}, null, 1) + '\n';

const out = path.join(root, 'schema/settings.json');
const isMain = process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname);
if (isMain) {
  const text = render(), have = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (process.argv.includes('--check')) { if (have !== text) { console.error('schema/settings.json is out of date: run npm run schema'); process.exit(1); } console.log('schema/settings.json is current'); }
  else { fs.writeFileSync(out, text); console.log(`wrote schema/settings.json (${SETTINGS.length} settings, ${PRESET_LIST.length} presets)`); }
}

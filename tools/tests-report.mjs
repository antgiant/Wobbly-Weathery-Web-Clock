// Writes docs/TESTS.md: what every test suite covers, and where the time goes, from the timings a test run records.
//   node tests/run.mjs all  (with TEST_ARTIFACTS=dir)  ->  dir/timings.json  (CI writes dir/timings-1of3.json ... one per share)
//   node tools/tests-report.mjs dir/timings*.json [--log ci-log.txt]   ->  docs/TESTS.md
// --log reads the "where the time went" tables from CI job logs instead (several logs, one per share, may be given).
import fs from 'fs';
import path from 'path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const args = process.argv.slice(2);
const files = args.filter((a) => a.endsWith('.json')), logs = []; for (let i = 0; i < args.length; i++) if (args[i] === '--log') logs.push(args[++i]);
const label = (args.find((a) => a.startsWith('--label=')) || '').slice(8) || 'this machine';

let browser = [], unit = [], when = '', node = '';
for (const f of files) { const j = JSON.parse(fs.readFileSync(f, 'utf8')); browser.push(...j.browser); if (j.unit?.length) unit = j.unit; when = j.when || when; node = j.node || node; }
for (const f of logs) {
  const text = fs.readFileSync(f, 'utf8');
  for (const m of text.matchAll(/^(?:\S+\s+)?  ([a-z][a-z-]*)\s+(\d+)\s+([\d.]+)\s+(\d+)\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)\s*$/gm)) {
    if (m[1] === 'all' || m[1] === 'suite') continue;
    browser.push({ name: m[1], checks: +m[2], ms: +m[3] * 1000, opens: +m[4], openMs: +m[5] * 1000, waitMs: +m[6] * 1000, otherMs: +m[7] * 1000 });
  }
  const u = [...text.matchAll(/^(?:\S+\s+)?  ok\s{4}([a-z][a-z-]*)\s+(\d+) checks\s+(\d+) ms\s*$/gm)]; if (u.length) unit = u.map((m) => ({ name: m[1], checks: +m[2], ms: +m[3] }));
}
if (!browser.length) { console.error('no timings: give a timings.json or --log'); process.exit(1); }

// what each suite says it covers, and its tier, from the suite files themselves
const meta = {};
for (const f of fs.readdirSync(path.join(root, 'tests/browser')).filter((x) => x.endsWith('.test.mjs'))) {
  const src = fs.readFileSync(path.join(root, 'tests/browser', f), 'utf8');
  const n = /export const name = '([^']+)'/.exec(src)?.[1], c = /export const covers = '((?:[^'\\]|\\.)*)'/.exec(src)?.[1], tier = /export const tier = 'fast'/.test(src) ? 'quick' : 'full only';
  if (n) meta[n] = { covers: (c || '').replace(/\\'/g, "'"), tier };
}
const s = (ms) => (ms / 1000).toFixed(1);
const rows = [...browser].sort((a, b) => b.ms - a.ms);
const sum = (k) => rows.reduce((a, b) => a + (b[k] || 0), 0);
let md = `# What is tested, and how long it takes

Generated by \`tools/tests-report.mjs\` from a full test run (${label}, ${when ? when.slice(0, 10) : 'undated'}${node ? ', Node ' + node : ''}). Do not edit by hand: re-run the tool.
Times are seconds. **Opening** is the time to get each page ready (the first sky picture is a heavy software-WebGL computation); **waiting** is
deliberate waits for the page to do something; **other** is everything else (checks, screenshots, reading the page). **Quick** suites are part of \`npm run test:quick\`
(each trimmed to its core); \`npm test\` runs only the suites the changed files can affect (\`tests/impact.mjs\`). CI runs everything, in three shares side by side.

## Browser suites (real page in headless Chromium, software WebGL)

| suite | tier | checks | pages | total | opening | waiting | other | what it covers |
|---|---|---:|---:|---:|---:|---:|---:|---|
`;
for (const b of rows) md += `| ${b.name} | ${(meta[b.name] || {}).tier || ''} | ${b.checks} | ${b.opens} | ${s(b.ms)} | ${s(b.openMs)} | ${s(b.waitMs)} | ${s(b.otherMs)} | ${(meta[b.name] || {}).covers || b.covers || ''} |\n`;
md += `| **all** | | ${sum('checks')} | ${sum('opens')} | **${s(sum('ms'))}** | ${s(sum('openMs'))} | ${s(sum('waitMs'))} | ${s(sum('otherMs'))} | |\n\n`;
const tot = sum('ms') || 1;
md += `Of the browser time, **${Math.round(100 * sum('openMs') / tot)}% is opening pages** (${sum('opens')} pages, about ${s(sum('openMs') / Math.max(1, sum('opens')) )} s each), **${Math.round(100 * sum('waitMs') / tot)}% is deliberate waiting**, and ${Math.round(100 * sum('otherMs') / tot)}% is everything else.\n\n`;
if (unit.length) {
  md += `## Unit tests (plain Node, no browser)\n\n| file | checks | ms |\n|---|---:|---:|\n`;
  for (const u of unit) md += `| ${u.name} | ${u.checks} | ${u.ms} |\n`;
  md += `| **all** | ${unit.reduce((a, b) => a + b.checks, 0)} | ${unit.reduce((a, b) => a + b.ms, 0)} |\n\n`;
}
md += `## Where it could be faster

- **Fewer page opens.** Every page costs about the same to get ready, so the suites with the most pages cost the most; checks that only need a different time or setting could reuse one page.
- **Shorter waits.** Waits are fixed pauses; waiting for the event (the next frame, a message) is shorter and steadier.
- **Keep the shares balanced.** CI's wall time is its slowest share. The suites are dealt to the three shares by cost (FULL_COST in tests/run.mjs, longest first to the lightest share): when a suite's time changes or a suite is added, copy its total from the table above into FULL_COST.
`;
fs.mkdirSync(path.join(root, 'docs'), { recursive: true });
fs.writeFileSync(path.join(root, 'docs/TESTS.md'), md);
console.log(`wrote docs/TESTS.md (${rows.length} suites)`);
